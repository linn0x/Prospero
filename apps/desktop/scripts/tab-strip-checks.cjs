const assert = require("node:assert/strict");
const delay = ms => new Promise(resolve => setTimeout(resolve, ms));

module.exports = async ({ window, run, wait, click, fill, screenshot, sessionIds }) => {
  const wc = window.webContents;
  window.setSize(1800, 1000);
  await wait("Boolean(document.querySelector('.workspace-dock-aside'))");
  await wait("!document.querySelector('.workspace-dock-sheet')");
  await run("window.prospero.updateSettings({theme:'light'})");
  await run("document.querySelector('.context-dock-resizer').dispatchEvent(new KeyboardEvent('keydown',{key:'End',bubbles:true}))");
  await delay(250);
  const order = selector => run(`Array.from(document.querySelectorAll(${JSON.stringify(selector)})).sort((a,b)=>Number(a.style.order)-Number(b.style.order)).map(el=>el.dataset.tabId)`);
  const bounds = selector => run(`(() => {const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2),left:r.left,right:r.right}})()`);
  const drag = async (start, x, cancel = false) => {
    wc.sendInputEvent({ type: "mouseMove", x: start.x, y: start.y }); await delay(80);
    wc.sendInputEvent({ type: "mouseDown", button: "left", clickCount: 1, x: start.x, y: start.y }); await delay(80);
    wc.sendInputEvent({ type: "mouseMove", button: "left", x: Math.round(x), y: start.y }); await delay(100);
    assert.equal(await run("Boolean(document.querySelector('[data-sorting]'))"), true);
    if (cancel) wc.sendInputEvent({ type: "keyDown", keyCode: "Escape" });
    wc.sendInputEvent({ type: "mouseUp", button: "left", clickCount: 1, x: Math.round(x), y: start.y });
    await wait("!document.querySelector('[data-sorting]')"); await delay(300);
  };
  const dockSelector = ".context-dock-tabs [data-tab-id]";
  await wait("document.querySelectorAll('.context-dock-tabs [data-tab-id]').length>=7");
  await run("window.__tabEditor=document.querySelector('.project-code-editor');window.__tabTerminal=document.querySelector('.dock-terminal .xterm')");
  const original = await order(dockSelector);
  const terminal = await bounds('#dock-tab-terminal');
  const firstDocument = await bounds('.context-dock-tabs [data-slot="project-file-tab"]');
  await drag(terminal, firstDocument.left + 2);
  const mixed = await order(dockSelector);
  assert.equal(mixed[0], "tool:terminal");
  assert.deepEqual(new Set(mixed), new Set(original));
  const documentTab = await bounds('.context-dock-tabs [data-slot="project-file-tab"]');
  const terminalNow = await bounds('#dock-tab-terminal');
  await drag(documentTab, terminalNow.left + 2);
  const documentFirst = await order(dockSelector);
  assert.match(documentFirst[0], /^document:/);
  assert.equal(documentFirst[1], "tool:terminal");
  const beforeCancel = await order(dockSelector);
  await drag(await bounds('#dock-tab-terminal'), firstDocument.right + 180, true);
  assert.deepEqual(await order(dockSelector), beforeCancel);
  assert.equal(await run("window.__tabEditor===document.querySelector('.project-code-editor') && window.__tabTerminal===document.querySelector('.dock-terminal .xterm')"), true);
  await click('[aria-label="隐藏工具栏"]'); await click('[aria-label="切换工具栏"]');
  assert.deepEqual(await order(dockSelector), beforeCancel, "Mixed order survives hiding the dock");
  await fill('[data-slot="project-file-filter"]', 'workspace.ts');
  assert.equal(await run("document.querySelector('[title=\"README.md\"].project-tree-row').getClientRects().length"), 0);
  assert(await run("document.querySelector('[title=\"src/workspace.ts\"].project-tree-row').getClientRects().length"));
  await click('[aria-label="清除文件筛选"]');
  assert.equal(await run("document.querySelector('[title=\"src\"].project-tree-row').getAttribute('aria-expanded')"), "true");
  await screenshot("tabs-files-light");
  await run("(() => {const prefs=JSON.parse(localStorage.getItem('prospero.contextDock.v1'));prefs.width=780;prefs.autoWidth=false;localStorage.setItem('prospero.contextDock.v1',JSON.stringify(prefs))})()");

  const reload = async ids => {
    await run(`localStorage.setItem('prospero.openSessions',${JSON.stringify(JSON.stringify(ids))});localStorage.setItem('prospero.activeSession',${JSON.stringify(ids[0])});`);
    await new Promise(resolve => { wc.once("did-finish-load", resolve); wc.reload(); });
    await wait(`document.querySelectorAll('.workspace-tab').length===${ids.length}`);
    await delay(200);
  };
  await reload(sessionIds.slice(0, 2));
  const spacious = await run("document.querySelector('.workspace-tab').getBoundingClientRect().width");
  await reload(sessionIds.slice(0, 9));
  const compact = await run("document.querySelector('.workspace-tab').getBoundingClientRect().width");
  assert(compact < spacious - 20 && compact >= 112, JSON.stringify({ spacious, compact }));
  await reload(sessionIds);
  const rail = '.topbar-workspace-tabs .tab-strip-viewport';
  await wait("Boolean(document.querySelector('.topbar-workspace-tabs[data-overflow]'))");
  assert.equal(await run("document.documentElement.scrollWidth>innerWidth"), false);
  const before = await run(`document.querySelector('${rail}').scrollLeft`);
  const position = await bounds(rail);
  wc.sendInputEvent({ type: "mouseWheel", x: position.x, y: position.y, deltaY: -220, deltaX: 0, canScroll: true });
  await wait(`document.querySelector('${rail}').scrollLeft>${before}`);
  await click('.topbar-workspace-tabs [aria-label="向后滚动标签"]');
  await click('.topbar-workspace-tabs [aria-label="所有标签"]');
  await run("[...document.querySelectorAll('.tab-strip-menu [role=menuitem]')].at(-1).click()");
  await wait(`document.getElementById('workspace-tab-${sessionIds.at(-1)}').getAttribute('aria-selected')==='true'`);
  const lastVisible = await run(`(() => {const r=document.getElementById('workspace-tab-${sessionIds.at(-1)}').getBoundingClientRect(),p=document.querySelector('${rail}').getBoundingClientRect();return r.left>=p.left-1&&r.right<=p.right+1})()`);
  assert.equal(lastVisible, true);
  await run(`document.querySelector('${rail}').scrollLeft=0`);
  const activeBeforeDrag = await run("localStorage.getItem('prospero.activeSession')");
  const first = await bounds(`[id="workspace-tab-${sessionIds[0]}"]`), third = await bounds(`[id="workspace-tab-${sessionIds[2]}"]`);
  await drag(first, third.right - 2);
  const saved = await run("JSON.parse(localStorage.getItem('prospero.openSessions'))");
  assert.equal(saved[2], sessionIds[0]);
  assert.equal(await run("localStorage.getItem('prospero.activeSession')"), activeBeforeDrag, "Dragging an inactive tab does not switch the conversation");
  await drag(await bounds(`[id="workspace-tab-${sessionIds[1]}"]`), third.right - 2, true);
  assert.deepEqual(await run("JSON.parse(localStorage.getItem('prospero.openSessions'))"), saved);
  await run(`document.getElementById('workspace-tab-${sessionIds[0]}').focus();document.getElementById('workspace-tab-${sessionIds[0]}').dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',ctrlKey:true,shiftKey:true,bubbles:true}))`);
  await wait(`JSON.parse(localStorage.getItem('prospero.openSessions'))[1]==='${sessionIds[0]}'`);
  const reordered = await run("JSON.parse(localStorage.getItem('prospero.openSessions'))");
  await new Promise(resolve => { wc.once("did-finish-load", resolve); wc.reload(); });
  await wait(`document.querySelectorAll('.workspace-tab').length===${sessionIds.length}`);
  assert.deepEqual(await order('.workspace-tab'), reordered);
  await run(`document.querySelector('${rail}').scrollLeft=0`);
  const edgeStart = await bounds(`[id="workspace-tab-${reordered[0]}"]`), edgeBounds = await bounds(rail);
  wc.sendInputEvent({ type: "mouseDown", button: "left", clickCount: 1, x: edgeStart.x, y: edgeStart.y }); await delay(80);
  wc.sendInputEvent({ type: "mouseMove", button: "left", x: Math.round(edgeBounds.right - 3), y: edgeStart.y });
  await wait(`document.querySelector('${rail}').scrollLeft>50`);
  wc.sendInputEvent({ type: "keyDown", keyCode: "Escape" });
  wc.sendInputEvent({ type: "mouseUp", button: "left", clickCount: 1, x: Math.round(edgeBounds.right - 3), y: edgeStart.y });
  await wait("!document.querySelector('[data-sorting]')");
  assert.deepEqual(await run("JSON.parse(localStorage.getItem('prospero.openSessions'))"), reordered);
  await run(`document.querySelector('${rail}').scrollLeft=0`);
  wc.sendInputEvent({ type: "mouseWheel", x: position.x, y: position.y, deltaY: 0, deltaX: -120, canScroll: true });
  await wait(`document.querySelector('${rail}').scrollLeft>0`);
  assert.equal(await run(`(() => {const event=new WheelEvent('wheel',{deltaY:100,ctrlKey:true,cancelable:true,bubbles:true});document.querySelector('${rail}').dispatchEvent(event);return event.defaultPrevented})()`), false);
  // Exercise macOS CSS clearance/no-drag hit regions on the Windows renderer.
  // Native AppKit traffic lights and trackpad hardware still require a Mac.
  await run("document.documentElement.dataset.platform='darwin';document.querySelector('.windows-titlebar').style.display='none'");
  const mac = await run("(() => {const r=document.querySelector('.topbar-workspace-tabs').getBoundingClientRect();return {left:r.left,top:r.top,region:getComputedStyle(document.querySelector('.workspace-tab-main')).webkitAppRegion,overflow:document.documentElement.scrollWidth>innerWidth}})()");
  assert.equal(mac.region, 'no-drag'); assert.equal(mac.overflow, false); assert(mac.left>=80 || mac.top>=44);
  await screenshot("tabs-macos-layout");
  window.setSize(700, 740); await delay(250);
  mac.compactTop = await run("document.querySelector('.topbar-workspace-tabs').getBoundingClientRect().top");
  assert(mac.compactTop >= 44, "Compact Mac windows keep the traffic-light row clear");
  assert.equal(await run("document.documentElement.scrollWidth>innerWidth"), false);
  window.setSize(1800, 1000); await delay(250);
  await run("document.documentElement.dataset.platform='win32';document.querySelector('.windows-titlebar').style.display=''");
  await click('#workspace-tab-ui-project-session');
  await click('[title="README.md"].project-tree-row');
  await wait("Boolean(document.querySelector('.project-markdown-preview h1'))");
  await screenshot("tabs-sessions-light");
  await run("window.prospero.updateSettings({theme:'dark'})"); await delay(600); await screenshot("tabs-sessions-dark");
  return { spacious, compact, count: sessionIds.length, mac, checks: ["mixed file/terminal pointer reorder", "portal document drag", "cancel restores order", "editors and terminal retained", "file filter preserves expansion", "adaptive tab widths", "wheel and overflow menu", "active tab reveal", "session reorder persistence", "keyboard reorder", "edge auto-scroll", "horizontal trackpad and pinch gestures", "macOS CSS clearance"] };
};
